alumno = {}  # Creamos un diccionario vacío

nombre = input("Ingrese el nombre: ")  # Pedimos el nombre del alumno
edad = input("Ingrese la edad: ")  # Pedimos la edad del alumno
curso = input("Ingrese el curso: ")  # Pedimos el curso del alumno

alumno["nombre"] = nombre  # Guardamos el nombre en el diccionario
alumno["edad"] = edad  # Guardamos la edad en el diccionario
alumno["curso"] = curso  # Guardamos el curso en el diccionario

print(alumno)  # Mostramos toda la información del alumno